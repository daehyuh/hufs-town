export type TranslationKey = keyof typeof messages.ko;
const englishMessages: Record<TranslationKey, string> = messages.en;
type Variables = Record<string, string | number>;
type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, variables?: Variables) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

function browserStorage(): Pick<Storage, "getItem" | "setItem"> | undefined {
  try {
    return typeof window === "undefined" ? undefined : window.localStorage;
  } catch {
    return undefined;
  }
}

export function readLanguage(storage = browserStorage()): Language {
  try {
    const saved = storage?.getItem(LANGUAGE_STORAGE_KEY);
    return saved === "en" ? "en" : "ko";
  } catch {
    return "ko";
  }
}

export function persistLanguage(
  language: Language,
  storage = browserStorage(),
) {
  try {
    storage?.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // The language still works for this session when storage is unavailable.
  }
}

export function translate(
  language: Language,
  key: TranslationKey,
  variables: Variables = {},
) {
  const unavailable =
    language === "en" ? "Text is unavailable." : "문구를 표시할 수 없어요.";
  const template =
    (language === "en" ? englishMessages[key] : messages.ko[key]) ??
    messages.ko[key] ??
    unavailable;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(variables[name] ?? ""),
  );
}

export function formatNumber(language: Language, value: number) {
  return new Intl.NumberFormat(language === "en" ? "en-US" : "ko-KR").format(
    value,
  );
}

export function formatDate(
  language: Language,
  value: string | number | Date,
  options: Intl.DateTimeFormatOptions = { dateStyle: "medium" },
) {
  return new Intl.DateTimeFormat(
    language === "en" ? "en-US" : "ko-KR",
    options,
  ).format(new Date(value));
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => readLanguage());
  const setLanguage = useCallback((next: Language) => {
    persistLanguage(next);
    setLanguageState(next);
  }, []);
  const t = useCallback(
    (key: TranslationKey, variables?: Variables) =>
      translate(language, key, variables),
    [language],
  );

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = language;
      document.title = t("landing.title");
      document
        .querySelector<HTMLMetaElement>('meta[name="description"]')
        ?.setAttribute("content", t("landing.description"));
    }
  }, [language, t]);

  const value = useMemo(
    () => ({ language, setLanguage, t }),
    [language, setLanguage, t],
  );
  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context)
    throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}

export function localizedErrorText(
  language: Language,
  detail: string,
  key: TranslationKey | undefined,
  translateKey: (key: TranslationKey) => string,
) {
  return language === "ko" && detail
    ? detail
    : key
      ? translateKey(key)
      : detail;
}

export function koreanErrorDetail(cause: unknown) {
  return cause instanceof Error && /[가-힣]/.test(cause.message)
    ? cause.message
    : "";
}

export function useLocalizedError() {
  const { language, t } = useLanguage();
  const [detail, setDetail] = useState("");
  const [key, setKey] = useState<TranslationKey>();
  const message = localizedErrorText(language, detail, key, t);
  const clear = useCallback(() => {
    setDetail("");
    setKey(undefined);
  }, []);
  const setMessage = useCallback((value: string) => {
    setDetail(value);
    setKey(undefined);
  }, []);
  const setFailure = useCallback((cause: unknown, fallback: TranslationKey) => {
    setDetail(koreanErrorDetail(cause));
    setKey(fallback);
  }, []);
  const setResource = useCallback(
    (fallback: TranslationKey, diagnostic = "") => {
      setDetail(koreanErrorDetail(new Error(diagnostic)));
      setKey(fallback);
    },
    [],
  );
  return { message, clear, setMessage, setFailure, setResource };
}

export function useOptionalLanguage() {
  return useContext(LanguageContext);
}

export function LanguagePicker() {
  const { language, setLanguage, t } = useLanguage();
  return (
    <label className="language-picker">
      <span className="sr-only">{t("language.label")}</span>
      <select
        aria-label={t("language.label")}
        value={language}
        onChange={(event) => setLanguage(event.currentTarget.value as Language)}
      >
        <option value="ko">{t("language.korean")}</option>
        <option value="en">{t("language.english")}</option>
      </select>
    </label>
  );
}
